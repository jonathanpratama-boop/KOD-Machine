"""Render research/LIQ_REBOUND_v1/run/RESULT.json as REPORT.md (presentation only; written before the run).

python3 research/LIQ_REBOUND_v1/report.py
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def pc(x, d=2):
    return "n/a" if x is None else f"{x * 100:+.{d}f}%"


def usd(x):
    return "n/a" if x is None else f"{x:,.0f}"


ROWS = (
    ("A1", "A1 maker, licensed IDR exchange"),
    ("A2", "A2 base, market orders"),
    ("A3", "A3 eToro real crypto (reported only)"),
    ("S1_delay4h", "S1 stress: entry 4h after signal"),
    ("S2", "S2 stress: doubled slippage"),
)


def account_table(accts: dict, bh: dict) -> list[str]:
    out = [
        (
            "| Account | End equity | Net return | CAGR | Max drawdown | Mean exposure | Turnover / yr | Trades | "
            "Win rate | Mean / median trade | Worst trade | P&L w/o top 3 |"
        ),
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for key, label in ROWS:
        a = accts[key]
        out.append(
            f"| {label} | {usd(a['end_equity'])} | {pc(a['net_return'])} | {pc(a['cagr'])} | "
            f"{pc(a['max_drawdown'])} | {a['mean_exposure']:.1%} | "
            f"{a.get('turnover_per_year', 0) or 0:.1f}x | {a['trades']} | {a.get('win_rate', 0):.0%} | "
            f"{pc(a.get('mean_net'))} / {pc(a.get('median_net'))} | {pc(a.get('worst_net'))} | "
            f"{usd(a.get('pnl_without_top3'))} |"
        )
    out.append("| Cash | 10,000 | +0.00% | +0.00% | 0.00% | 0% | 0 | 0 | | | | |")
    out.append(
        f"| Buy-and-hold BTC/ETH 50/50 (A2 costs) | {usd(10_000 * (1 + bh['equal_weight']))} | "
        f"{pc(bh['equal_weight'])} | | {pc(bh['equal_weight_max_drawdown'])} | 100% | | | | | | |"
    )
    return out


def period(name: str, p: dict) -> list[str]:
    a2 = p["accounts"]["A2"]
    b, pl, m, mf = p["bootstrap_A2"], p["placebo_A2"], p["mechanism"], p["missed_fill_A2"]
    L = [
        f"## {name}",
        "",
        *account_table(p["accounts"], p["buy_and_hold_A2"]),
        "",
        (
            f"- Episodes (7-day gap): {p['episodes']}. Mean net trade (A2) {pc(b['mean'])}; episode-cluster bootstrap "
            f"95% interval {pc(b['lower95'])} to {pc(b['upper95'])}, one-sided 95% lower bound "
            f"{pc(b['lower_one_sided_95'])}."
        ),
        (
            f"- Random-entry placebo (same coins and counts, {pl['draws']} draws): median {pc(pl['p50'])}, 90th "
            f"percentile {pc(pl['p90'])}; matched unconditional mean of a 72h hold {pc(pl['matched_unconditional_mean'])}."
        ),
        (
            f"- Mechanism: cascade trades {m['cascade_trades']} (mean gross {pc(m['cascade_gross_mean'])}, net A2 "
            f"{pc(m['cascade_net_mean_A2'])}) vs control (drop-only, no recent cascade) trades {m['control_trades']} (mean gross "
            f"{pc(m['control_gross_mean'])}, net A2 {pc(m['control_net_mean_A2'])})."
        ),
        (
            f"- Missed-fill stress (each entry fails with p = {mf['p_fail']}, {mf['draws']} draws): median end equity "
            f"{usd(mf['median_end'])}, 5th percentile {usd(mf['p05_end'])}, share above start {mf['share_above_start']:.0%}."
        ),
        (
            f"- A2 exits: {a2.get('exit_types', {})}; skips and events: {a2.get('events', {})}; CVaR 95% of trades "
            f"{pc(a2.get('cvar95_net'))}; best trade {pc(a2.get('best_net'))}."
        ),
        f"- By coin: {json.dumps(a2.get('by_symbol', {}))}",
        f"- By year: {json.dumps(a2.get('by_year', {}))}",
        "",
    ]
    return L


def main() -> int:
    r = json.loads((HERE / "run/RESULT.json").read_text())
    L = [
        "# LIQ_REBOUND_v1: buying BTC/ETH spot after forced-deleveraging cascades",
        "",
        (
            f"Ran {r['ran_at']} at commit `{r['commit']}` on the frozen protocol (PROTOCOL.md, protocol.json). One run. "
            "Simulation only, development data only (no row dated 2024-01-01 or later)."
        ),
        "",
        f"## Verdict: {r['verdict']}",
        "",
        "| Gate | Result |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in r["gates"].items()],
        "",
        *period("Discovery (signals 2020-09-01..2022-12-31)", r["discovery"]),
        *period("2023 provisional screen (an already-used year)", r["screen_2023"]),
        "## What this does and does not show",
        "",
        (
            "- Development data only; KOD and the literature have looked at these years. A pass would be a candidate "
            "for validation, never proof; a fail ends this rule (no retune)."
        ),
        "- Binance USDT prices stand in for IDR exchange fills; the IDR basis during cascades is unmeasured.",
        "- Open-interest files were regenerated by the archive (2026-03-18) and are not guaranteed point-in-time.",
        "- A live open-interest source reachable from Indonesia is not yet verified.",
        (
            "- eToro counts only for positions tagged as real crypto at 1x; at its standard-tier costs (A3) the rule's "
            "economics are shown above."
        ),
        "",
    ]
    (HERE / "REPORT.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:20]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
